/**
 * Device Model
 * Biometric device (phone) registered by employer.
 * Only one active device per company (or branch, configurable).
 */
const mongoose = require('mongoose');
const crypto = require('crypto');

const DEVICE_TYPES = ['phone', 'tablet', 'pos', 'scanner'];

const deviceSchema = new mongoose.Schema({
    // ============ Tenant ============
    company: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Company',
        required: [true, 'Company is required'],
        index: true
    },
    branch: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Branch',
        default: null,
        index: true
        // null = company-wide device
        // set = branch-specific device
    },

    // ============ Identity ============
    name: {
        type: String,
        required: [true, 'Device name is required'],
        trim: true,
        maxlength: [100, 'Device name cannot exceed 100 characters']
    },
    deviceId: {
        type: String,
        required: [true, 'Device ID is required'],
        unique: true,
        trim: true
        // Unique hardware ID (generated by client or biometric SDK)
    },
    type: {
        type: String,
        enum: {
            values: DEVICE_TYPES,
            message: 'Device type must be one of: ' + DEVICE_TYPES.join(', ')
        },
        default: 'phone'
    },

    // ============ Auth (API key for device requests) ============
    apiKey: {
        type: String,
        required: true,
        select: false  // never returned
        // Hashed before save
    },
    apiKeyPrefix: {
        type: String
        // First 8 chars of the raw key (for display/identification)
    },

    // ============ Assignment ============
    assignedTo: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        default: null
        // The employee whose phone this is
    },

    // ============ Status ============
    isActive: {
        type: Boolean,
        default: true
    },
    lastSeenAt: {
        type: Date,
        default: null
    },
    lastSeenIp: {
        type: String,
        default: null
    },

    // ============ Metadata ============
    registeredBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
    },
    registeredAt: {
        type: Date,
        default: Date.now
    },
    deactivatedAt: {
        type: Date,
        default: null
    },
    deactivatedBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        default: null
    }
});

// ============================================================
// Indexes
// ============================================================
// Only one active device per company (or per branch if branch-scoped)
deviceSchema.index(
    { company: 1, branch: 1, isActive: 1 },
    {
        unique: true,
        partialFilterExpression: { isActive: true }
        // This enforces "only 1 active device per company/branch"
        // partialFilterExpression means: unique among docs where isActive = true
    }
);

// Query: active devices
deviceSchema.index({ isActive: 1, lastSeenAt: -1 });

// Query: devices assigned to a user
deviceSchema.index({ assignedTo: 1, isActive: 1 });

// ============================================================
// Pre-save: hash API key
// ============================================================
deviceSchema.pre('save', async function (next) {
    if (!this.isModified('apiKey')) return next();

    try {
        const bcrypt = require('bcryptjs');
        // Store prefix for identification
        this.apiKeyPrefix = this.apiKey.substring(0, 8);
        // Hash full key
        const salt = await bcrypt.genSalt(12);
        this.apiKey = await bcrypt.hash(this.apiKey, salt);
        next();
    } catch (err) {
        next(err);
    }
});

// ============================================================
// Static: generate a new API key (raw — caller must save the model)
// ============================================================
deviceSchema.statics.generateApiKey = function () {
    return crypto.randomBytes(32).toString('hex');
};

// ============================================================
// Method: verify an API key
// ============================================================
deviceSchema.methods.verifyApiKey = async function (candidateKey) {
    const bcrypt = require('bcryptjs');
    return bcrypt.compare(candidateKey, this.apiKey);
};

// ============================================================
// Static: deactivate all active devices for a company/branch
// (used when registering a new device)
// ============================================================
deviceSchema.statics.deactivateAll = async function (companyId, branchId = null, userId = null) {
    const filter = { company: companyId, isActive: true };
    if (branchId) filter.branch = branchId;
    else filter.branch = null; // company-wide devices only

    return this.updateMany(filter, {
        $set: {
            isActive: false,
            deactivatedAt: new Date(),
            deactivatedBy: userId
        }
    });
};

// ============================================================
// Static: find active device for a company/branch
// ============================================================
deviceSchema.statics.findActive = function (companyId, branchId = null) {
    const filter = { company: companyId, isActive: true };
    if (branchId) filter.branch = branchId;
    else filter.branch = null;
    return this.findOne(filter);
};

// ============================================================
// Method: mark as seen
// ============================================================
deviceSchema.methods.markSeen = function (ip) {
    return this.updateOne({
        $set: { lastSeenAt: new Date(), lastSeenIp: ip }
    });
};

// ============================================================
// Method: safe public JSON
// ============================================================
deviceSchema.methods.toPublicJSON = function () {
    return {
        id: this._id,
        name: this.name,
        deviceId: this.deviceId,
        type: this.type,
        apiKeyPrefix: this.apiKeyPrefix,
        branch: this.branch,
        assignedTo: this.assignedTo,
        isActive: this.isActive,
        lastSeenAt: this.lastSeenAt,
        registeredAt: this.registeredAt
    };
};

deviceSchema.set('toJSON', { virtuals: true });
deviceSchema.set('toObject', { virtuals: true });

// Expose constants
deviceSchema.statics.DEVICE_TYPES = DEVICE_TYPES;

module.exports = mongoose.model('Device', deviceSchema);